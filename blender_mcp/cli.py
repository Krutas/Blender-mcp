def _common_connection(parser):
    parser.add_argument("--host", default=os.environ.get("BLENDER_MCP_HOST", "127.0.0.1"))
    parser.add_argument("--port", type=int, default=int(os.environ.get("BLENDER_MCP_PORT", "9876")))
    parser.add_argument("--timeout", type=float, default=float(os.environ.get("BLENDER_MCP_TIMEOUT", "120")))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="blender-mcp",
        description="Blender MCP - drive a running Blender from any MCP-capable agent.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent(
            """\
            quick start:
              blender-mcp install          # copy the add-on into Blender
              blender-mcp headless         # or: start Blender with no GUI
              blender-mcp connect          # register with Hermes
              blender-mcp doctor           # check every link in the chain
            """
        ),
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("serve", help="run the MCP server on stdio")
    p.set_defaults(func=cmd_serve)

    p = sub.add_parser("install", help="install the Blender add-on")
    p.add_argument("--blender-dir", help="override the scripts/addons directory")
    p.add_argument("--blender-binary", default="blender")
    p.add_argument("--enable", action="store_true", help="print the headless enable command")
    p.set_defaults(func=cmd_install)

    p = sub.add_parser("headless", help="launch Blender in background with the server running")
    p.add_argument("--blend", help=".blend file to open")
    p.add_argument("--blender-binary", default="blender")
    p.add_argument("--blender-dir")
    p.add_argument("--launcher", help="where to write the generated launcher script")
    p.add_argument("--log")
    p.add_argument("--foreground", action="store_true", help="stay attached to Blender's output")
    p.add_argument("--print-only", action="store_true", help="print the command and exit")
    _common_connection(p)
    p.set_defaults(func=cmd_headless)

    p = sub.add_parser("connect", help="register the server with Hermes (hermes mcp add)")
    p.add_argument("--name", default="blender")
    p.add_argument("--python", default=sys.executable)
    p.add_argument("--print-only", action="store_true")
    _common_connection(p)
    p.set_defaults(func=cmd_connect)

    p = sub.add_parser("config", help="print the config.yaml snippet for manual registration")
    p.add_argument("--python", default=sys.executable)
    _common_connection(p)
    p.set_defaults(func=cmd_config)

    p = sub.add_parser("doctor", help="check Blender, the add-on, the socket and the MCP SDK")
    p.add_argument("--blender-binary", default="blender")
    p.add_argument("--blender-dir")
    p.add_argument("--name", default="blender", help="Hermes mcp_servers key to look for")
    _common_connection(p)
    p.set_defaults(func=cmd_doctor)

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
