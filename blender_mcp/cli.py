def cmd_serve(args) -> int:
    from .server import main as serve_main

    return serve_main([])


def cmd_install(args) -> int:
    addons_dir = resolve_addons_dir(args.blender_dir, args.blender_binary)
    addons_dir.mkdir(parents=True, exist_ok=True)
    target = addons_dir / f"{ADDON_MODULE_NAME}.py"
    shutil.copyfile(ADDON_SOURCE, target)

    print(f"Add-on installed: {target}")
    print()
    print("Next steps in Blender:")
    print("  1. Edit > Preferences > Add-ons > search 'Blender MCP' > tick the checkbox")
    print("  2. 3D Viewport > Sidebar (N) > 'Blender MCP' tab")
    print("  3. Press 'Start Blender MCP Server' (starts automatically by default)")
    if args.enable:
        print()
        print("Enable it headlessly with:")
        print(f"  blender --background --python-expr \"import addon_utils; addon_utils.enable('{ADDON_MODULE_NAME}')\"")
    return 0


HEADLESS_LAUNCHER = '''\
"""Generated by `blender-mcp headless` - started inside Blender."""
import sys
import time

import bpy

sys.path.insert(0, {addons_dir!r})
import {module} as addon

started = addon.start_server({host!r}, {port!r}, {timeout!r})
print(
    "[blender-mcp] server " + ("started" if started else "already running")
    + " on {host}:{port} | blender " + bpy.app.version_string
    + " background=" + str(bpy.app.background)
    + " file=" + (bpy.data.filepath or "<unsaved>"),
    flush=True,
)

# `blender --background` runs this script and then quits, and it never pumps
# bpy.app.timers. So this loop *is* Blender's main loop for the life of the
# process: it keeps the process alive and dispatches queued commands on the real
# main thread, which is what bpy requires.
try:
    while True:
        addon.pump_once()
        time.sleep(0.02)
except KeyboardInterrupt:
    print("[blender-mcp] shutting down", flush=True)
    addon.stop_server()
'''


def cmd_headless(args) -> int:
    binary = args.blender_binary
    if shutil.which(binary) is None:
        raise SystemExit(f"{binary!r} is not on PATH.")

    addons_dir = resolve_addons_dir(args.blender_dir, binary)
    addons_dir.mkdir(parents=True, exist_ok=True)
    # Keep a copy next to the launcher so the module import always resolves,
    # even if the user never ran `blender-mcp install`.
    shutil.copyfile(ADDON_SOURCE, addons_dir / f"{ADDON_MODULE_NAME}.py")

    launcher = Path(args.launcher or (Path.home() / ".hermes" / "cache" / "blender-mcp-headless.py"))
    launcher.parent.mkdir(parents=True, exist_ok=True)
    launcher.write_text(
        HEADLESS_LAUNCHER.format(
            addons_dir=str(addons_dir),
            module=ADDON_MODULE_NAME,
            host=args.host,
            port=args.port,
            timeout=args.timeout,
        )
    )

    command = [binary, "--background"]
    if args.blend:
        command.append(str(Path(args.blend).expanduser()))
    command += ["--python", str(launcher)]

    print("Launching:", " ".join(command), file=sys.stderr)
    if args.print_only:
        print(" ".join(command))
        return 0

    if args.foreground:
        return subprocess.call(command)

    log = Path(args.log or (Path.home() / ".hermes" / "cache" / "blender-mcp-headless.log"))
    log.parent.mkdir(parents=True, exist_ok=True)
    with open(log, "ab") as handle:
        process = subprocess.Popen(
            command,
            stdout=handle,
            stderr=subprocess.STDOUT,
            # Detach so Blender outlives the shell that launched it.
            start_new_session=True,
        )
    print(f"Blender running headless pid={process.pid}, log: {log}")
    print(f"Now listening on {args.host}:{args.port} once it finishes starting (~2-5s).")
    return 0


def _hermes_command(args) -> list[str]:
    return [
        "hermes",
        "mcp",
        "add",
        args.name,
        "--command",
        args.python,
        "--env",
        f"BLENDER_MCP_HOST={args.host}",
        f"BLENDER_MCP_PORT={args.port}",
        f"BLENDER_MCP_TIMEOUT={args.timeout}",
        "--args",
        "-m",
        "blender_mcp",
        "serve",
    ]


def cmd_connect(args) -> int:
    command = _hermes_command(args)
    if args.print_only:
        print(" ".join(command))
        return 0
    if shutil.which("hermes") is None:
        raise SystemExit("Hermes is not on PATH; run with --print-only and add the server by hand.")
    print("Running:", " ".join(command), file=sys.stderr)
    return subprocess.call(command)


CONFIG_SNIPPET = """\
mcp_servers:
  blender:
    command: "{python}"
    args: ["-m", "blender_mcp", "serve"]
    env:
      BLENDER_MCP_HOST: "{host}"
      BLENDER_MCP_PORT: "{port}"
      BLENDER_MCP_TIMEOUT: "{timeout}"
    timeout: 180
"""


def cmd_config(args) -> int:
    print(
        CONFIG_SNIPPET.format(
            python=args.python, host=args.host, port=args.port, timeout=str(int(args.timeout) + 60)
        )
    )
    return 0


def _hermes_registration(config: Path, name: str) -> tuple[bool, str]:
    """Is ``name`` a key directly under the top-level ``mcp_servers:`` block?

    A plain substring search gives false positives (the string "blender" appears
    elsewhere in most configs), so walk the YAML by indentation instead of
    pulling in PyYAML for one check.
    """
    in_block = False
    block_indent = 0
    try:
        lines = config.read_text(errors="replace").splitlines()
    except OSError as exc:
        return False, str(exc)

    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        if not in_block:
            if stripped in {"mcp_servers:", "mcp_servers"}:
                in_block = True
                block_indent = indent
            continue
        if indent <= block_indent:
            break  # left the block without finding it
        if indent == block_indent + 2 and stripped.split(":", 1)[0] == name:
            return True, str(config)
    return False, f"no 'mcp_servers.{name}' entry in {config}"


def cmd_doctor(args) -> int:
    from .client import BlenderClient

    ok = True

    def report(label, good, detail=""):
        nonlocal ok
        ok = ok and good
        print(f"[{'ok ' if good else 'FAIL'}] {label}{(' - ' + detail) if detail else ''}")

    binary = shutil.which(args.blender_binary)
    report("blender on PATH", binary is not None, binary or "not found")

    if binary:
        version = blender_binary_version(binary)
        report("blender version detected", version is not None, version or "unknown")

    try:
        addons_dir = resolve_addons_dir(args.blender_dir, args.blender_binary)
        installed = (addons_dir / f"{ADDON_MODULE_NAME}.py").is_file()
        report("add-on installed", installed, str(addons_dir / f"{ADDON_MODULE_NAME}.py"))
    except SystemExit as exc:
        report("add-on installed", False, str(exc))

    client = BlenderClient(host=args.host, port=args.port, connect_timeout=2.0)
    info = client.status()
    report("add-on server reachable", info is not None, f"{args.host}:{args.port}")
    if info:
        print()
        print(json.dumps(info, indent=2))

    try:
        import mcp  # noqa: F401

        report("mcp SDK importable", True)
    except ImportError as exc:
        report("mcp SDK importable", False, str(exc))

    hermes_home = Path(os.environ.get("HERMES_HOME") or Path.home() / ".hermes")
    config = hermes_home / "config.yaml"
    if config.is_file():
        registered, detail = _hermes_registration(config, args.name)
        report(f"registered in hermes config as '{args.name}'", registered, detail)
    else:
        report("hermes config present", False, str(config))

    print()
    print("doctor:", "all checks passed" if ok else "see FAIL lines above")
    return 0 if ok else 1


