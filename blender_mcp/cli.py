"""Command line entry point: ``blender-mcp <command>``."""

from __future__ import annotations

import argparse
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

ADDON_MODULE_NAME = "blender_mcp_addon"
ADDON_SOURCE = Path(__file__).with_name("addon.py")


# --------------------------------------------------------------------------
# locating Blender's per-user script directories
# --------------------------------------------------------------------------


def _config_root() -> Path:
    system = platform.system()
    if system == "Windows":
        base = os.environ.get("APPDATA") or str(Path.home() / "AppData" / "Roaming")
        return Path(base) / "Blender Foundation" / "Blender"
    if system == "Darwin":
        return Path.home() / "Library" / "Application Support" / "Blender"
    base = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(base) / "blender"


def blender_versions() -> list[str]:
    """Version directories Blender has already written under the user config."""
    root = _config_root()
    if not root.is_dir():
        return []
    versions = [p.name for p in root.iterdir() if p.is_dir() and re.fullmatch(r"\d+\.\d+", p.name)]
    return sorted(versions, key=lambda v: tuple(int(x) for x in v.split(".")), reverse=True)


def blender_binary_version(binary: str = "blender") -> str | None:
    """Ask the blender binary for its major.minor version (e.g. '5.0')."""
    try:
        out = subprocess.run(
            [binary, "--version"], capture_output=True, text=True, timeout=30, check=False
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    match = re.search(r"Blender\s+(\d+)\.(\d+)", out)
    return f"{match.group(1)}.{match.group(2)}" if match else None


def resolve_addons_dir(explicit: str | None, binary: str = "blender") -> Path:
    if explicit:
        return Path(explicit).expanduser()
    version = blender_binary_version(binary) or (blender_versions() or [None])[0]
    if version is None:
        raise SystemExit(
            "Could not work out which Blender version directory to use.\n"
            "Install Blender and put it on PATH, or pass --blender-dir /path/to/config/<x.y>."
        )
    return _config_root() / version / "scripts" / "addons"


